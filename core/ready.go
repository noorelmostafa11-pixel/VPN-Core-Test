package core

import (
	"errors"
	"os"
)

func writeReady(path string, b []byte) error {
	if _, e := os.Stat(path); e == nil {
		return errors.New("READY_FILE_EXISTS")
	}
	f, e := os.OpenFile(path+".tmp", os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if e != nil {
		return e
	}
	defer os.Remove(path + ".tmp")
	_, e = f.Write(b)
	ce := f.Close()
	if e != nil {
		return e
	}
	if ce != nil {
		return ce
	}
	return os.Rename(path+".tmp", path)
}

